            x, y = symbols('x y')
            lisdang = ['1']
            dang = random.choice(lisdang)

            if dang == '1':
                # Bước 3: Suy nghĩ tìm cách random bài toán
                # Chọn số mũ n từ 4 đến 6 để giữ độ phức tạp vừa phải
                n = random.choice([4, 5, 6])
                # Chọn hệ số k cho y (ví dụ: x - y, x - 2y,...)
                k = random.choice([1, 2])
                # Chọn dấu (cộng hoặc trừ)
                dau = random.choice([-1, 1])

                # Biểu thức nhị thức gốc
                bieu_thuc_goc = (x + dau * k * y)**n
                # Khai triển đa thức
                da_thuc_p = expand(bieu_thuc_goc)

                # Đáp án đúng
                kq_dung = bieu_thuc_goc
                da = '$%s$' % (latex(kq_dung))

                # Các đáp án nhiễu (Bước 4: Điều chỉnh phương án sai)
                s = [
                    '$%s$' % (latex((x - dau * k * y)**n)),
                    '$%s$' % (latex((x + k * y)**(n-1))),
                    '$%s$' % (latex((k * x + dau * y)**n)),
                    '$%s$' % (latex((x + (k+1) * dau * y)**n)),
                    '$%s$' % (latex((x + dau * k * y)**(n+1)))
                ]

                # Loại bỏ các trường hợp trùng lặp với đáp án đúng nếu có
                s = [item for item in s if item != da]

                das1 = random.choice(s)
                s.remove(das1)
                das2 = random.choice(s)
                s.remove(das2)
                das3 = random.choice(s)

                # Câu hỏi (Bước 2: Viết lại theo mẫu)
                noidungcauhoi = ('''Đa thức $P\\left(x\\right) = %s$ là khai triển của nhị thức nào dưới đây?'''
                                 % (latex(da_thuc_p)))

                # Các đáp án
                da_d = ('\\True ' + str(da))
                da_s1 = str(das1)
                da_s2 = str(das2) 
                da_s3 = str(das3) 

                # Đưa các đáp án vào 1 danh sách chọn ngẫu nhiên
                list_1 = [da_d, da_s1, da_s2, da_s3]
                random.shuffle(list_1)

                # Nội dung lời giải chi tiết
                loigiai = ('''Áp dụng công thức khai triển nhị thức Newton: \\\\
                             $\\left(a+b\\right)^n = \\sum_{k=0}^{n} C_n^k a^{n-k} b^k$. \\\\
                             Xét đa thức $P\\left(x\\right) = %s$. \\\\
                             Ta thấy các hệ số tương ứng với hàng thứ $%s$ của tam giác Pascal (hoặc tính các giá trị $C_{%s}^k$). \\\\
                             Dấu của các số hạng và lũy thừa của $y$ cho thấy đây là khai triển của biểu thức %s.\\\\
                             Vậy $P\\left(x\\right) = $%s.'''
                           % (latex(da_thuc_p), latex(n), latex(n), da, da))

            # Xuất câu trắc nghiệm
            content = ('\\begin{minipage}{\\textwidth} \n'
                       '\\begin{ex}\n' + str(noidungcauhoi) + 
                       '\\choice \n'
                       '{' + str(list_1[0]) + '}\n'
                       '{' + str(list_1[1]) + '}\n'
                       '{' + str(list_1[2]) + '}\n'
                       '{' + str(list_1[3]) + '}\n'
                       '\\loigiai{' + str(loigiai) + '}\n'
                       '\\end{ex}\n \\end{minipage} \n\n')
            return content

