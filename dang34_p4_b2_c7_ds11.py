            # Danh sách các hàm lượng giác để random phần mũ
            f_list = [sin(x), cos(x), tan(x)]
            u = random.choice(f_list)

            # Hàm số chính: y = e^u
            y = exp(u)

            # Tính đạo hàm y' = u' * e^u
            u_prime = diff(u, x)
            y_prime = u_prime * exp(u)

            # Tạo các phương án nhiễu (distractors)
            # Sai dấu, thiếu u', hoặc sai hàm lượng giác
            s1 = -u_prime * exp(u)
            s2 = u * exp(u)
            s3 = diff(u_prime, x) * exp(u)

            # Chuyển đổi sang latex và xử lý định dạng dấu
            def format_latex(expr):
                s = latex(expr)
                # Xử lý hiển thị dấu theo yêu cầu: -- thành +, +- thành -
                s = s.replace('--', '+').replace('+-', '-')
                return s

            da_dung = f'${format_latex(y_prime)}$'
            das1 = f'${format_latex(s1)}$'
            das2 = f'${format_latex(s2)}$'
            das3 = f'${format_latex(s3)}$'

            # B2: Viết nội dung câu hỏi và lời giải theo mẫu
            noidungcauhoi = f'Tính đạo hàm của hàm số $y = {format_latex(y)}$.'

            # Nội dung lời giải
            loigiai = (f'Ta có $y\' = ({format_latex(u)})\' \\cdot e^{{{format_latex(u)}}} = \\left({format_latex(u_prime)}\\right) \\cdot e^{{{format_latex(u)}}}$.')

            # Thiết lập trắc nghiệm
            da_d = '\\True ' + da_dung
            list_1 = [da_d, das1, das2, das3]
            random.shuffle(list_1)

