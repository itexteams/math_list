                # Các đáp án
                da_d = ('\\True $' + da_dung_val + '$')
                da_s1 = '$' + wrong_samples[0] + '$'
                da_s2 = '$' + wrong_samples[1] + '$'
                da_s3 = '$' + wrong_samples[2] + '$'

                # Đưa các đáp án vào 1 danh sách chọn ngẫu nhiên
                list_1 = [da_d, da_s1, da_s2, da_s3]
                random.shuffle(list_1)

