                # Khởi tạo tập giá trị cho tử số (p) và mẫu số (q) của cot(alpha)
                p_list = [-4, -3, -2, -1, 1, 2, 3, 4]
                q_list = [1, 2, 3, 4, 5]

                # Random phân số p/q sao cho tối giản và không bị trùng giá trị sin và cos (tránh |p| == q)
                while True:
                    p = random.choice(p_list)
                    q = random.choice(q_list)
                    if math.gcd(abs(p), q) == 1 and abs(p) != q:
                        break

                cot_val = Rational(p, q)

                # Tính toán các giá trị
                # cos^2(alpha) = p^2 / (p^2 + q^2)
                cos_sq = Rational(p**2, p**2 + q**2)

                # Giá trị độ lớn của cos(alpha)
                cos_abs = sqrt(cos_sq)

                # Giá trị độ lớn của sin(alpha) để tạo nhiễu
                sin_abs = sqrt(Rational(q**2, p**2 + q**2))

                # Các đáp án trắc nghiệm
                du = ['$\\pm %s$' % latex(cos_abs)]
                da = random.choice(du)

                # Các phương án nhiễu: chỉ lấy dương, chỉ lấy âm, giá trị của sin, giá trị nghịch đảo
                s = ['$%s$' % latex(cos_abs),
                     '$-%s$' % latex(cos_abs),
                     '$\\pm %s$' % latex(sin_abs),
                     '$\\pm %s$' % latex(1/cos_abs)]

                das1 = random.choice(s)
                s.remove(das1)
                das2 = random.choice(s)
                s.remove(das2)
                das3 = random.choice(s)

                # Câu hỏi
